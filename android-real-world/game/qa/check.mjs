import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-dev-shm-usage']});
const context=await browser.newContext({viewport:{width:740,height:416},acceptDownloads:true});
const p=await context.newPage();p.setDefaultTimeout(90000);p.setDefaultNavigationTimeout(90000);
const errors=[];
p.on('pageerror',e=>{errors.push(e.message);console.error('PAGE',e);});
p.on('console',m=>{if(m.type()==='error')console.error('CONSOLE',m.text().slice(0,920));});
p.on('response',r=>{if(r.status()>=400)console.error('HTTP',r.status(),r.url());});
try {
await p.addInitScript(() => localStorage.setItem('utm-quality','0'));
await p.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
await p.waitForFunction(()=>window.campusQA&&campusQA().triangles>1000,{},{timeout:45000});
await p.screenshot({path:'qa/01-aerial.png'});
console.log('Intro',await p.evaluate(()=>campusQA().triangles));
await p.locator('#begin').click();
await p.waitForTimeout(1300);
await p.screenshot({path:'qa/02-walk.png'});
assert.equal(await p.evaluate(()=>campusQA().mode),'walk');
const coord=await p.evaluate(()=>campusQA().world);
await p.locator('#viewport').click({position:{x:510,y:300}});
await p.keyboard.down('KeyW');await p.waitForTimeout(2700); console.log('walk movement',await p.evaluate(()=>campusQA().world),coord,await p.evaluate(()=>campusQA().keyboard)); await p.keyboard.up('KeyW');
assert.ok(await p.evaluate((old)=>Math.hypot(campusQA().world[0]-old[0],campusQA().world[2]-old[2]),coord)>.25);
const beforeStick=await p.evaluate(()=>campusQA().world);
const joy=await p.locator('#joystick').boundingBox();
await p.mouse.move(joy.x+39,joy.y+39);
await p.mouse.down();await p.mouse.move(joy.x+39,joy.y+3,{steps:3});await p.waitForTimeout(1200);await p.mouse.up();
assert.ok(await p.evaluate((old)=>Math.hypot(campusQA().world[0]-old[0],campusQA().world[2]-old[2]),beforeStick)>.25);
await p.locator('#view').click();
assert.equal(await p.locator('#modeName').textContent(),'FIRST PERSON');
await p.locator('#mapButton').click();
await p.getByRole('button',{name:'MJIIT',exact:false}).click();
await p.locator('#visit').click();
await p.waitForTimeout(550);
await p.screenshot({path:'qa/03-mjiit.png'});
assert.ok(Math.abs((await p.evaluate(()=>campusQA().world[0]))+262)<3);
assert.ok(await p.evaluate(()=>campusQA().collides(-325.59,-108.77)));
await p.locator('#settingsButton').click();
await p.locator('#quality').selectOption({label:'Performance'});
await p.locator('#weather').selectOption('rain');
await p.locator('#stats').check();
await p.locator('#settingsPanel .close').click();
await p.waitForTimeout(650);
await p.screenshot({path:'qa/04-rain.png'});
assert.match(await p.locator('#diagnostic').textContent(),/WebGL2 · Performance/);
assert.equal(await p.evaluate(()=>campusQA().weather),'rain');
await p.locator('#photoButton').click();
const dl=p.waitForEvent('download',{timeout:30000});
await p.locator('#capture').click();
await (await dl).saveAs('qa/captured.jpg');
await p.locator('#photoButton').click();
await p.locator('#mapButton').click();
await p.getByRole('button',{name:'Gaussian gallery',exact:false}).click();
await p.locator('#visit').click();
await p.waitForFunction(()=>window.campusQA&&campusQA().splats===113648,{},{timeout:60000});
await p.waitForTimeout(2800);
await p.screenshot({path:'qa/05-gallery.png'});
assert.match(await p.locator('#scanText').textContent(),/113,648/);
await p.locator('#exhibitSwitch').click();
await p.waitForFunction(()=>window.campusQA&&campusQA().splats===122490,{},{timeout:90000,polling:250});
await p.waitForTimeout(5800);
await p.screenshot({path:'qa/06-outdoor.png'});
assert.match(await p.locator('#scanText').textContent(),/122,490/);
await p.locator('#exhibitSwitch').click();
await p.locator('#scanFile').setInputFiles('public/plant.splat');
await p.waitForFunction(()=>document.querySelector('#scanText').textContent.includes('local file'),{},{timeout:45000});
await p.locator('#exitScan').click();
assert.equal(await p.evaluate(()=>campusQA().mode),'walk');
assert.deepEqual(errors,[]);
console.log('Verified landscape intro, WASD, pointer joystick, camera, navigation, collisions, graphics/weather, photo download and Gaussian gallery/local import.');
} finally {await browser.close();}
